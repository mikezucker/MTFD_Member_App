import Foundation
@main struct ContractTests {
    struct Contract: Decodable {
        let home: TrainingWorkspaceHome
        let detail: TrainingWorkspaceDetail
        let instructor: TrainingWorkspaceDetail
        let draft: TrainingWorkspaceDetail
    }
    struct GuidedContract:Decodable {
        let home:GuidedHome
        let session:GuidedSessionResponse
        let library:GuidedLibrary
        let results:GuidedResults
    }
    struct TourDrillContract: Decodable {
        let session: GuidedSessionResponse
        let review: Review
        let requirements: GuidedSkillsResponse
        struct Review: Decodable { let attended: Int; let absent: Int; let passed: Int; let needsWork: Int; let incomplete: Int }
    }
    static func main() throws {
        guard CommandLine.arguments.count == 2 else { fatalError("Pass the contract fixture generated by the isolated backend tests") }
        let fixture = try JSONDecoder.mtfdTrainingDecoder.decode(Contract.self, from: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1])))
        assert(fixture.home.success && !fixture.home.canCreate)
        assert(fixture.detail.course.delivery == "CBT")
        assert(fixture.detail.course.progressStatus == "COMPLETED")
        assert(fixture.detail.course.completions?.first?.scorePercent == 80)
        assert(fixture.detail.course.completions?.first?.durationMinutes == 90)
        assert(fixture.instructor.canManage == true && !(fixture.instructor.roster ?? []).isEmpty)
        assert(fixture.draft.draft?.title == "Edited draft")
        let encoded = try JSONEncoder().encode(fixture.draft.draft!)
        let body = try JSONSerialization.jsonObject(with: encoded) as! [String: Any]
        assert(body["questions"] != nil && body["catalogRoles"] != nil)
        let learnerData = try JSONSerialization.jsonObject(with: JSONSerialization.data(withJSONObject: ["success":false,"error":"No access"])) as! [String: Any]
        let failure = try JSONDecoder().decode(TrainingWorkspaceMutation.self, from: JSONSerialization.data(withJSONObject: learnerData))
        assert(!failure.success && failure.error == "No access")
        let legacy = try JSONDecoder.mtfdTrainingDecoder.decode(TrainingWorkspaceDetail.self, from: Data(#"{"success":true,"legacy":true,"course":{"id":"old","title":"Historical course"}}"#.utf8))
        assert(legacy.legacy && legacy.course.id == "old")
        let guided = try JSONDecoder.mtfdTrainingDecoder.decode(GuidedContract.self,from:Data(contentsOf:URL(fileURLWithPath:CommandLine.arguments[1]+".guided")))
        assert(guided.session.session.participants.count == 15)
        assert(guided.session.session.jprs.count == 2)
        assert(guided.session.session.locked)
        assert(guided.home.topics.contains{Set($0.jprs.compactMap(\.jprId)).count == 2})
        assert(guided.library.versions.contains{$0.status == "DRAFT"})
        assert(guided.results.results.count == 2 && guided.results.results.allSatisfy{$0.outcome == "INCOMPLETE"})
        let oldVersion=guided.library.versions.first!
        var reviewObject=try JSONSerialization.jsonObject(with:JSONEncoder().encode(oldVersion)) as! [String:Any]
        reviewObject["reviewToken"]=String(repeating:"a",count:64);reviewObject["approvalIssue"]="Complete equipment before approving this JPR."
        let reviewed=try JSONDecoder().decode(GuidedVersion.self,from:JSONSerialization.data(withJSONObject:reviewObject))
        assert(reviewed.reviewToken==String(repeating:"a",count:64) && reviewed.approvalIssue?.contains("equipment")==true)
        let firstTopic = guided.home.topics.first!
        assert(firstTopic.matches(search: firstTopic.title, categoryId: ""))
        assert(!firstTopic.matches(search: "__missing_course__", categoryId: ""))
        assert(!firstTopic.matches(search: "", categoryId: "__missing_category__"))
        assert(firstTopic.latestJprs.count == Set(firstTopic.jprs.compactMap(\.jprId)).count)
        let pendingHome = try JSONDecoder().decode(GuidedHome.self, from: Data(#"{"canCreate":true,"topics":[],"members":[],"groups":[],"sessions":[],"pendingCourses":[{"id":"pending","title":"Needs review","totalJprs":2,"category":{"id":"ladder","name":"Ladders"}}]}"#.utf8))
        assert(pendingHome.pendingCourses?.first?.totalJprs == 2)
        let member = guided.session.session.participants.first!
        assert(guided.session.session.outcome(guided.session.session.jprs[0],member) == "Passed")
        let skills = try JSONDecoder.mtfdTrainingDecoder.decode(GuidedSkillsResponse.self, from: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1]+".skills")))
        assert(skills.requirements.count == 1)
        assert(skills.requirements[0].completed == 3 && skills.requirements[0].required == 2)
        assert(skills.requirements[0].percent == 100 && skills.requirements[0].history.count == 3)
        let annual = try JSONDecoder.mtfdTrainingDecoder.decode(GuidedSkillsResponse.self, from: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1]+".annual")))
        assert(annual.requirements.count == 1 && annual.requirements[0].periodYear != nil)
        assert(annual.requirements[0].completed == 1 && annual.requirements[0].required == 2)
        assert(annual.sessions?.first?.versionIds == [annual.requirements[0].versionId])
        assert(annual.sessions?.first?.status == "IN_PROGRESS")
        let legacySkills = try JSONDecoder().decode(GuidedSkillsResponse.self, from: Data(#"{"requirements":[],"sessions":[{"id":"legacy","title":"Existing scheduled session","durationMinutes":60}]}"#.utf8))
        assert(legacySkills.sessions?.first?.versionIds == nil)
        let groups = [GuidedGroup(name: "Station 1", userIds: ["a","b"]), GuidedGroup(name: "Station 2", userIds: ["c"])]
        assert(AnnualTrainingBoardSelection.memberIds("", groups: groups, dutyIds: []) == nil)
        assert(AnnualTrainingBoardSelection.memberIds("group:Station 2", groups: groups, dutyIds: []) == ["c"])
        assert(AnnualTrainingBoardSelection.memberIds("member:b", groups: groups, dutyIds: []) == ["b"])
        assert(AnnualTrainingBoardSelection.memberIds("duty", groups: groups, dutyIds: []) == [])
        assert(AnnualTrainingBoardSelection.memberIds("duty", groups: groups, dutyIds: ["b","c"]) == ["b","c"])
        assert(AnnualTrainingBoardSelection.memberIds("group:missing", groups: groups, dutyIds: []) == [])
        let drill = try JSONDecoder.mtfdTrainingDecoder.decode(TourDrillContract.self, from: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1]+".tour-drill")))
        let review = drill.session.session.review
        precondition(review.attended == drill.review.attended && review.absent == drill.review.absent)
        precondition(review.passed == drill.review.passed && review.needsWork == drill.review.needsWork && review.incomplete == drill.review.incomplete)
        precondition(review.attended == 3 && review.absent == 1 && review.passed == 1 && review.needsWork == 1 && review.incomplete == 1)
        precondition(drill.requirements.requirements.count == 4 && drill.requirements.requirements.allSatisfy { $0.nextStep == "Complete" })
        let dates = ISO8601DateFormatter()
        let due = dates.date(from: "2026-11-02T05:00:00Z")!
        var requirement = GuidedSkillRequirement(id: "fixture", userId: "fixture", member: "Synthetic member", versionId: "fixture", courseId: "fixture", number: "TEST", title: "Fixture", revision: 1, required: 2, completed: 0, percent: 0, dueAt: due, history: [])
        precondition(requirement.nextStep == "Evaluation due")
        precondition(!requirement.isOverdue(at: dates.date(from: "2026-11-03T04:59:59Z")!))
        precondition(requirement.isOverdue(at: dates.date(from: "2026-11-03T05:00:00Z")!))
        // Use actual mixed session outcomes to confirm the next-step wording.
        for member in drill.session.session.participants where member.attended != false {
            let outcome = drill.session.session.outcome(drill.session.session.jprs[0], member)
            let result = outcome == "Passed" ? "PASS" : outcome == "Incomplete" ? "INCOMPLETE" : "FAIL"
            requirement = GuidedSkillRequirement(id: "fixture", userId: member.id, member: member.name, versionId: "fixture", courseId: "fixture", number: "TEST", title: "Fixture", revision: 1, required: 2, completed: result == "PASS" ? 1 : 0, percent: 0, dueAt: due, history: [GuidedSkillHistory(id: "fixture", outcome: result, completedAt: due, evaluator: "Fixture")])
            precondition(requirement.nextStep == (result == "PASS" ? "More repetitions due" : result == "FAIL" ? "Practice & reevaluate" : "Finish evaluation"))
        }
        print("PASS: native mixed-tour summary matches backend grading; member next steps and Eastern due-day boundaries")
        let oldCourse = try JSONDecoder().decode(TrainingWorkspaceCourse.self, from: Data(#"{"id":"old","title":"Legacy API","delivery":"PRACTICAL","assigned":true,"progressStatus":"IN_PROGRESS","creditedMinutes":0,"pendingForm":false}"#.utf8))
        precondition(oldCourse.displayProgressPercent == nil, "An older API must not invent partial progress")
        let progressCourse = try JSONDecoder().decode(TrainingWorkspaceCourse.self, from: Data(#"{"id":"progress","title":"Course progress","delivery":"CBT","assigned":true,"progressStatus":"IN_PROGRESS","progressPercent":50,"creditedMinutes":0,"pendingForm":false}"#.utf8))
        precondition(progressCourse.displayProgressPercent == 50)
        precondition(fixture.home.courses.contains { $0.progressStatus == "COMPLETED" && $0.displayProgressPercent == 100 })
        print("PASS: native course progress decodes additive API fields and preserves older API compatibility")
        print("PASS: all-member, saved group, individual and unloaded-tour native selection")
        print("PASS: annual period, pinned skill, scheduled session metadata and older API compatibility")
        print("PASS: real guided session, Word draft library, 15 participants, revision and incomplete-result contracts")
        print("PASS: iPhone decodes real backend learner/instructor/draft/legacy contracts and preserves quiz/credit fields")
    }
}
