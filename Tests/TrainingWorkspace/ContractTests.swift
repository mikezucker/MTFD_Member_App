import Foundation
@main struct ContractTests {
    struct Contract: Decodable {
        let home: TrainingWorkspaceHome
        let detail: TrainingWorkspaceDetail
        let instructor: TrainingWorkspaceDetail
        let draft: TrainingWorkspaceDetail
    }
    static func main() throws {
        guard CommandLine.arguments.count == 2 else { fatalError("Pass the contract fixture generated by the isolated backend tests") }
        let fixture = try JSONDecoder.mtfdTrainingDecoder.decode(Contract.self, from: Data(contentsOf: URL(fileURLWithPath: CommandLine.arguments[1])))
        assert(fixture.home.success && !fixture.home.canCreate)
        assert(fixture.detail.course.delivery == "CBT")
        assert(fixture.detail.course.progressStatus == "COMPLETED")
        assert(fixture.detail.course.completions?.first?.scorePercent == 80)
        assert(fixture.detail.course.completions?.first?.durationMinutes == 90)
        assert(fixture.instructor.canManage == true && !(fixture.instructor.roster ?? []).isEmpty)
        assert(fixture.draft.draft?.title == "Edited draft")
        let encoded = try JSONEncoder().encode(fixture.draft.draft!)
        let body = try JSONSerialization.jsonObject(with: encoded) as! [String: Any]
        assert(body["questions"] != nil && body["catalogRoles"] != nil)
        let learnerData = try JSONSerialization.jsonObject(with: JSONSerialization.data(withJSONObject: ["success":false,"error":"No access"])) as! [String: Any]
        let failure = try JSONDecoder().decode(TrainingWorkspaceMutation.self, from: JSONSerialization.data(withJSONObject: learnerData))
        assert(!failure.success && failure.error == "No access")
        let legacy = try JSONDecoder.mtfdTrainingDecoder.decode(TrainingWorkspaceDetail.self, from: Data(#"{"success":true,"legacy":true,"course":{"id":"old","title":"Historical course"}}"#.utf8))
        assert(legacy.legacy && legacy.course.id == "old")
        print("PASS: iPhone decodes real backend learner/instructor/draft/legacy contracts and preserves quiz/credit fields")
    }
}
