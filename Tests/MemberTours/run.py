from pathlib import Path
import subprocess,sys,tempfile
root=Path(__file__).resolve().parents[2]
api=(root/'Services/Network/APIClient.swift').read_text()
more=(root/'Features/More/Views/MoreView.swift').read_text()
header=(root/'Features/Dashboard/Views/DashboardHeaderView.swift').read_text()
def block(source,signature):
    start=source.index(signature); opening=source.index('{',start); depth=1; end=opening+1
    while depth:
        depth+=(source[end]=='{')-(source[end]=='}'); end+=1
    return source[start:end]
models='import Foundation\nenum APIClient {\n'+'\n'.join(block(api,s) for s in ['struct MemberTour:','struct CurrentMemberTourResponse:','struct Member: Decodable','struct MobileMemberPermissions:'])+'\n}\n'
models+='\n'.join(block(more,s).replace('private struct','struct',1) for s in ['private struct AdminTourRecord:','private struct AdminTourMember:','private struct AdminTourSnapshot:'])
subtitle=block(header,'private var headerSubtitle:').replace('private var','var',1)
models+='\nstruct HeaderSubject {let roleTitle:String;let stationTitle:String;let tourTitle:String?;'+subtitle+'}\n'
if len(sys.argv)!=2:raise SystemExit('Pass the .tours fixture generated by isolated backend tests.')
with tempfile.TemporaryDirectory(prefix='mtfd-tour-contract-') as d:
    d=Path(d);(d/'Production.swift').write_text(models)
    subprocess.run(['swiftc','-parse-as-library',str(d/'Production.swift'),str(root/'Tests/MemberTours/TourTests.swift'),'-o',str(d/'tests')],check=True)
    subprocess.run([str(d/'tests'),sys.argv[1]],check=True)
